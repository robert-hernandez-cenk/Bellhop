// Escapes text for HTML element content and quoted attribute values. Shared
// by the server-rendered pages: the status page and the web sign-in pages.
export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
