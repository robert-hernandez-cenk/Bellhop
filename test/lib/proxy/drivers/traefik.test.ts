// --- generation marker: stability and change detection (research.md R3) ----

test('generationMarkerName: stable across two renders of the same routes, and different when a route changes', () => {
  const routes = [route({ owner: { type: 'guest', name: 'app' } })];
  const first = render(routes, ctx(), CONFIG_PATH)[0].content;
  const second = render(routes, ctx(), CONFIG_PATH)[0].content;
  assert.equal(first, second, 'two renders of the same input must be byte-identical');
  assert.equal(generationMarkerName(first), generationMarkerName(second));

  const changed = [route({ owner: { type: 'guest', name: 'app' }, backend: { ip: '192.0.2.99', port: 80, insecureTls: false } })];
  const third = render(changed, ctx(), CONFIG_PATH)[0].content;
  assert.notEqual(generationMarkerName(first), generationMarkerName(third), 'a changed route must change the marker hash');
});

