// --- buildApiCheck, executed (T015): stubbed curl/sleep on PATH -------------
// Follows test/lib/proxy/file-driver.test.ts's sh + stub pattern: the
// generated script is executed for real under `sh`, with only `curl` and
// `sleep` stubbed on PATH (real mktemp/cp/mv). The stub curl answers from
// the captured fixtures in test/fixtures/traefik/ by URL.

const FIXTURES_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', '..', 'fixtures', 'traefik');
const ROUTER_ENABLED_FIXTURE = join(FIXTURES_DIR, 'router-enabled.json');
const ROUTER_DISABLED_FIXTURE = join(FIXTURES_DIR, 'router-disabled.json');
// A sentinel that never matches a real rendered router name, used as
// BELLHOP_TEST_BAD_ROUTER when every router in a test is meant to be healthy
// -- an empty value would make the stub's `*"$VAR"*` glob match everything.
const NO_BAD_ROUTER = 'bellhop-test-no-bad-router-sentinel';

function shAvailable(): boolean {
  const result = spawnSync('sh', ['-c', 'exit 0']);
  return result.error === undefined || result.error === null;
}

function posix(p: string): string {
  return p.replace(/\\/g, '/');
}

// A stub `curl` that answers a marker-middleware poll with a fixed HTTP
// status code (and, for the "000"/unreachable case, real curl's own
// non-zero exit -- see buildApiCheck's `set -e` comment above: an earlier
// version of this stub always exited 0 regardless of scenario, which never
// exercised the script's actual behavior under a real curl failure at all),
// and a router-body fetch by `cat`-ing one of two fixture files -- the "bad"
// one when the URL contains $BELLHOP_TEST_BAD_ROUTER (an env var set per
// test), the "good" one otherwise. `badRouterMode: 'fetch-fails'` makes the
// bad router's own fetch behave like a real curl connection failure too:
// nothing on stdout, a non-zero exit -- research.md's "a curl failure on a
// router fetch (empty body) counts as unhealthy" decision.
function writeCurlStub(
  stubDir: string,
  opts: { markerCode: string; markerExit?: number; badRouterMode?: 'disabled' | 'fetch-fails' }
): void {
  const markerExit = opts.markerExit ?? 0;
  const badRouterMode = opts.badRouterMode ?? 'disabled';
  const curlPath = join(stubDir, 'curl');
  const script = [
    '#!/bin/sh',
    'url=""',
    'for a in "$@"; do url="$a"; done',
    'case "$url" in',
    '  */middlewares/*)',
    `    printf '%s' '${opts.markerCode}'`,
    `    exit ${markerExit}`,
    '    ;;',
    '  */routers/*)',
    '    case "$url" in',
    '      *"$BELLHOP_TEST_BAD_ROUTER"*)',
    badRouterMode === 'fetch-fails' ? '        exit 7' : `        cat '${posix(ROUTER_DISABLED_FIXTURE)}'`,
    '        ;;',
    '      *)',
    `        cat '${posix(ROUTER_ENABLED_FIXTURE)}'`,
    '        ;;',
    '    esac',
    '    ;;',
    'esac',
  ].join('\n');
  writeFileSync(curlPath, script);
  chmodSync(curlPath, 0o755);
}

function writeSleepStub(stubDir: string): void {
  const sleepPath = join(stubDir, 'sleep');
  writeFileSync(sleepPath, '#!/bin/sh\nexit 0\n');
  chmodSync(sleepPath, 0o755);
}

