test('render: the contract example\'s wiki entry -- rule order, entry point, service, middlewares, tls.certResolver, and http service URL', () => {
  const wiki = route({
    owner: { type: 'guest', name: 'wiki' },
    hostnames: ['wiki.example.com', 'docs.example.com'],
    backend: { ip: '192.0.2.20', port: 8080, insecureTls: false },
  });

  // The body without the marker, built the same way render() computes its
  // own hash input -- the test recomputes the hash independently (via
  // node:crypto directly, not by importing render()'s internals) so this is
  // a real pin on the hashing behavior, not a tautology.
  const bodyWithoutMarker = [
    'http:',
    '  routers:',
    '    bellhop-route-wiki-example-com:',
    '      rule: Host(`wiki.example.com`) || Host(`docs.example.com`)',
    '      entryPoints:',
    '        - websecure',
    '      service: bellhop-route-wiki-example-com',
    '      middlewares:',
    '        - bellhop-forwarded-port',
    '      tls:',
    '        certResolver: cloudflare',
    '  services:',
    '    bellhop-route-wiki-example-com:',
    '      loadBalancer:',
    '        servers:',
    '          - url: http://192.0.2.20:8080',
    '  middlewares:',
    ...FORWARDED_PORT_MIDDLEWARE,
    '',
  ].join('\n');
  const contentWithoutMarker = `${HEADER}\n${bodyWithoutMarker}`;
  const hash = sha256First12(contentWithoutMarker);

  const expected = [
    HEADER,
    'http:',
    '  routers:',
    '    bellhop-route-wiki-example-com:',
    '      rule: Host(`wiki.example.com`) || Host(`docs.example.com`)',
    '      entryPoints:',
    '        - websecure',
    '      service: bellhop-route-wiki-example-com',
    '      middlewares:',
    '        - bellhop-forwarded-port',
    '      tls:',
    '        certResolver: cloudflare',
    '  services:',
    '    bellhop-route-wiki-example-com:',
    '      loadBalancer:',
    '        servers:',
    '          - url: http://192.0.2.20:8080',
    '  middlewares:',
    ...FORWARDED_PORT_MIDDLEWARE,
    `    bellhop-generation-${hash}:`,
    '      headers:',
    '        customRequestHeaders:',
    `          X-Bellhop-Generation: "${hash}"`,
    '',
  ].join('\n');

  assert.equal(renderOne(wiki), expected);
});

