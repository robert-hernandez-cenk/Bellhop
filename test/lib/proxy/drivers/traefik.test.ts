import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { parse, stringify } from 'yaml';
import { buildRoutes, buildProxyContext, parsePathPattern, type ProxyContext, type ProxyRoute } from '../../../../src/lib/proxy/routes.ts';
import { encodeHostname, generationMarkerName, render, routeName, routerNames, ruleValue } from '../../../../src/lib/proxy/drivers/traefik.ts';
import type { Inventory } from '../../../../src/lib/inventory.ts';

const HEADER = '# Generated by Bellhop sync-proxy. Do not edit: this file is replaced on every apply.';
const CONFIG_PATH = '/etc/traefik/dynamic/bellhop.yml';

function ctx(overrides: Partial<ProxyContext> = {}): ProxyContext {
  return {
    externalPort: 443,
    tls: {
      certificatePath: '/etc/letsencrypt/live/example.com/fullchain.pem',
      keyPath: '/etc/letsencrypt/live/example.com/privkey.pem',
    },
    certResolver: 'cloudflare',
    ...overrides,
  };
}

function route(overrides: Partial<ProxyRoute> & { owner: ProxyRoute['owner'] }): ProxyRoute {
  return {
    hostnames: [`${overrides.owner.name}.example.com`],
    backend: { ip: '192.0.2.30', port: 80, insecureTls: false },
    auth: { mode: 'ungated' },
    ...overrides,
  };
}

function renderOne(r: ProxyRoute, c: ProxyContext = ctx()): string {
  return render([r], c, CONFIG_PATH)[0].content;
}

// The forwarded-port middleware body, present in every rendered file
// regardless of routes (research.md R7).
const FORWARDED_PORT_MIDDLEWARE = ['    bellhop-forwarded-port:', '      headers:', '        customRequestHeaders:', '          X-Forwarded-Port: "443"'];

function sha256First12(content: string): string {
  return createHash('sha256').update(content).digest('hex').slice(0, 12);
}

// --- encodeHostname / ruleValue / name helpers -------------------------------

test('encodeHostname: lowercases, doubles "-", then turns "." into "-" -- injective, so two different hostnames never collide', () => {
  assert.equal(encodeHostname('Wiki.Example.com'), 'wiki-example-com');
  assert.equal(encodeHostname('a.b-c.example.com'), 'a-b--c-example-com');
  assert.equal(encodeHostname('a-b.c.example.com'), 'a--b-c-example-com');
  assert.notEqual(encodeHostname('a.b-c.example.com'), encodeHostname('a-b.c.example.com'));
});

test('routeName: bellhop-route-<encoded canonical hostname>', () => {
  assert.equal(routeName('wiki.example.com'), 'bellhop-route-wiki-example-com');
});

test('ruleValue: no backtick -> backtick-quoted', () => {
  assert.equal(ruleValue('wiki.example.com'), '`wiki.example.com`');
  assert.equal(ruleValue('/health'), '`/health`');
});

test('ruleValue: a value containing a backtick -> JSON.stringify (double-quoted Go-style escaping)', () => {
  const value = '/a`b"c\\d';
  assert.equal(ruleValue(value), JSON.stringify(value));
  assert.equal(ruleValue(value), '"/a`b\\"c\\\\d"');
});

// --- render: the contract's *wiki* entry (ungated, two hostnames) -----------

test('render: the contract example\'s wiki entry -- rule order, entry point, service, middlewares, tls.certResolver, and http service URL', () => {
  const wiki = route({
    owner: { type: 'guest', name: 'wiki' },
    hostnames: ['wiki.example.com', 'docs.example.com'],
    backend: { ip: '192.0.2.20', port: 8080, insecureTls: false },
  });

  // The body without the marker, built the same way render() computes its
  // own hash input -- the test recomputes the hash independently (via
  // node:crypto directly, not by importing render()'s internals) so this is
  // a real pin on the hashing behavior, not a tautology.
  const bodyWithoutMarker = [
    'http:',
    '  routers:',
    '    bellhop-route-wiki-example-com:',
    '      rule: Host(`wiki.example.com`) || Host(`docs.example.com`)',
    '      entryPoints:',
    '        - websecure',
    '      service: bellhop-route-wiki-example-com',
    '      middlewares:',
    '        - bellhop-forwarded-port',
    '      tls:',
    '        certResolver: cloudflare',
    '  services:',
    '    bellhop-route-wiki-example-com:',
    '      loadBalancer:',
    '        servers:',
    '          - url: http://192.0.2.20:8080',
    '  middlewares:',
    ...FORWARDED_PORT_MIDDLEWARE,
    '',
  ].join('\n');
  const contentWithoutMarker = `${HEADER}\n${bodyWithoutMarker}`;
  const hash = sha256First12(contentWithoutMarker);

  const expected = [
    HEADER,
    'http:',
    '  routers:',
    '    bellhop-route-wiki-example-com:',
    '      rule: Host(`wiki.example.com`) || Host(`docs.example.com`)',
    '      entryPoints:',
    '        - websecure',
    '      service: bellhop-route-wiki-example-com',
    '      middlewares:',
    '        - bellhop-forwarded-port',
    '      tls:',
    '        certResolver: cloudflare',
    '  services:',
    '    bellhop-route-wiki-example-com:',
    '      loadBalancer:',
    '        servers:',
    '          - url: http://192.0.2.20:8080',
    '  middlewares:',
    ...FORWARDED_PORT_MIDDLEWARE,
    `    bellhop-generation-${hash}:`,
    '      headers:',
    '        customRequestHeaders:',
    `          X-Bellhop-Generation: "${hash}"`,
    '',
  ].join('\n');

  assert.equal(renderOne(wiki), expected);
});

test('render: entry point is always [websecure], and middlewares lists bellhop-forwarded-port only for an ungated route', () => {
  const content = renderOne(route({ owner: { type: 'guest', name: 'app' } }));
  const doc = parse(content) as { http: { routers: Record<string, { entryPoints: string[]; middlewares: string[] }> } };
  const router = doc.http.routers['bellhop-route-app-example-com'];
  assert.deepEqual(router.entryPoints, ['websecure']);
  assert.deepEqual(router.middlewares, ['bellhop-forwarded-port']);
});

