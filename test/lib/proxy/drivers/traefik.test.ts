const HEADER = '# Generated by Bellhop sync-proxy. Do not edit: this file is replaced on every apply.';
const CONFIG_PATH = '/etc/traefik/dynamic/bellhop.yml';

function ctx(overrides: Partial<ProxyContext> = {}): ProxyContext {
  return {
    externalPort: 443,
    tls: {
      certificatePath: '/etc/letsencrypt/live/example.com/fullchain.pem',
      keyPath: '/etc/letsencrypt/live/example.com/privkey.pem',
    },
    certResolver: 'cloudflare',
    ...overrides,
  };
}

function route(overrides: Partial<ProxyRoute> & { owner: ProxyRoute['owner'] }): ProxyRoute {
  return {
    hostnames: [`${overrides.owner.name}.example.com`],
    backend: { ip: '192.0.2.30', port: 80, insecureTls: false },
    auth: { mode: 'ungated' },
    ...overrides,
  };
}

function renderOne(r: ProxyRoute, c: ProxyContext = ctx()): string {
  return render([r], c, CONFIG_PATH)[0].content;
}

// The forwarded-port middleware body, present in every rendered file
// regardless of routes (research.md R7).
const FORWARDED_PORT_MIDDLEWARE = ['    bellhop-forwarded-port:', '      headers:', '        customRequestHeaders:', '          X-Forwarded-Port: "443"'];

function sha256First12(content: string): string {
  return createHash('sha256').update(content).digest('hex').slice(0, 12);
}

// --- encodeHostname / ruleValue / name helpers -------------------------------

test('encodeHostname: lowercases, doubles "-", then turns "." into "-" -- injective, so two different hostnames never collide', () => {
  assert.equal(encodeHostname('Wiki.Example.com'), 'wiki-example-com');
  assert.equal(encodeHostname('a.b-c.example.com'), 'a-b--c-example-com');
  assert.equal(encodeHostname('a-b.c.example.com'), 'a--b-c-example-com');
  assert.notEqual(encodeHostname('a.b-c.example.com'), encodeHostname('a-b.c.example.com'));
});

test('routeName: bellhop-route-<encoded canonical hostname>', () => {
  assert.equal(routeName('wiki.example.com'), 'bellhop-route-wiki-example-com');
});

test('ruleValue: no backtick -> backtick-quoted', () => {
  assert.equal(ruleValue('wiki.example.com'), '`wiki.example.com`');
  assert.equal(ruleValue('/health'), '`/health`');
});

test('ruleValue: a value containing a backtick -> JSON.stringify (double-quoted Go-style escaping)', () => {
  const value = '/a`b"c\\d';
  assert.equal(ruleValue(value), JSON.stringify(value));
  assert.equal(ruleValue(value), '"/a`b\\"c\\\\d"');
});

