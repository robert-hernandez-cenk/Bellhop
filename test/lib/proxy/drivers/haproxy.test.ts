test('render: the contract example -> exact backends and map files', () => {
  const [backends, map] = renderInventory(exampleInventory());
  assert.equal(backends.content, EXPECTED_BACKENDS);
  assert.equal(map.content, EXPECTED_MAP);
});

test('render: zero routes -> each file is exactly the header line', () => {
  const [backends, map] = renderInventory(emptyInventory());
  assert.equal(backends.content, HEADER);
  assert.equal(map.content, HEADER);
});

test('render returns two owned FileSpecs -- backends at configPath, then the map beside it -- each owned by its first line', () => {
  const files = renderInventory(exampleInventory());
  assert.equal(files.length, 2);
  assert.deepEqual(
    files.map((f) => f.path),
    [CONFIG_PATH, MAP_PATH]
  );
  for (const file of files) {
    assert.equal(file.mode, 'owned');
    assert.equal(file.ownedHeader, HEADER);
    assert.equal(file.content.split('\n')[0], file.ownedHeader);
  }
});

test("render: an OIDC route renders identically to the same route ungated (no auth lines at all)", () => {
  const ungated = exampleInventory();
  ungated.externalSites = [{ name: 'nas', ip: '192.0.2.20', port: 443, subdomains: ['nas'] }];
  assert.deepEqual(renderInventory(exampleInventory()), renderInventory(ungated));
});

test("render: a forward-gated route throws naming the entry (the capability check's backstop)", () => {
  const forward = route({
    owner: { type: 'guest', name: 'app-lxc' },
    auth: { mode: 'forward', exemptPaths: [], rawExemptPaths: [] },
  });
  assert.throws(() => render([forward], ctx(), CONFIG_PATH), /^Error: HAProxy cannot enforce forward-auth for entry 'app-lxc'$/);
});

test('render: X-Forwarded-Port follows ctx.externalPort', () => {
  const [backends] = render([route({ owner: { type: 'guest', name: 'app-lxc' } })], ctx(8443), CONFIG_PATH);
  assert.match(backends.content, /^ {4}http-request set-header X-Forwarded-Port 8443$/m);
  assert.doesNotMatch(backends.content, /X-Forwarded-Port 443$/m);
});

test('render: map hostnames are lower-cased, canonical first; backend names keep their case', () => {
  const r = route({ owner: { type: 'guest', name: 'App-LXC' }, hostnames: ['App.Example.com', 'ALIAS.example.com'] });
  const [backends, map] = render([r], ctx(), CONFIG_PATH);
  assert.equal(map.content, [HEADER, 'app.example.com bellhop_guest_App-LXC', 'alias.example.com bellhop_guest_App-LXC'].join('\n'));
  assert.match(backends.content, /^backend bellhop_guest_App-LXC$/m);
});

test('render: never renders unauthenticatedPaths (an OIDC entry that also carries them)', () => {
  const inv = exampleInventory();
  inv.externalSites![0].unauthenticatedPaths = ['/api/*'];
  const [backends, map] = renderInventory(inv);
  assert.doesNotMatch(backends.content + map.content, /\/api/);
});

