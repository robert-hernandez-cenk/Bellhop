const HEADER = '# Generated by Bellhop sync-proxy for HAProxy. Do not edit: this file is replaced on every apply.';
// The nginx driver's own header -- deliberately different from HAProxy's, so
// a file the nginx driver left at a shared proxyConfigPath is refused.
const NGINX_HEADER = '# Generated by Bellhop sync-proxy. Do not edit: this file is replaced on every apply.';
const CONFIG_PATH = '/etc/haproxy/bellhop.cfg';
const MAP_PATH = '/etc/haproxy/bellhop.map';

// The contract's own example inventory ("Example"): an ungated guest with
// two hostnames, an insecureBackendTls host on 8006 (also the proxy host),
// and an OIDC-gated external site on 443.
function exampleInventory(): Inventory {
  return {
    domain: 'example.com',
    hosts: [
      {
        name: 'pve1',
        ssh_target: '192.0.2.2',
        ssh_user: 'root',
        proxy: true,
        ip: '192.0.2.2',
        port: 8006,
        subdomains: ['pve'],
        insecureBackendTls: true,
      },
    ],
    guests: [
      { name: 'web-lxc', type: 'lxc', vmid: 100, host: 'pve1', ip: '192.0.2.10', port: 8080, subdomains: ['web', 'www'] },
    ],
    externalSites: [
      {
        name: 'nas',
        ip: '192.0.2.20',
        port: 443,
        subdomains: ['nas'],
        authGroup: 'bellhop-admin-family',
        authMode: 'oidc',
        oidcRedirectUris: ['https://nas.example.com/callback'],
      },
    ],
  };
}

function emptyInventory(): Inventory {
  return {
    domain: 'example.com',
    hosts: [{ name: 'pve1', ssh_target: '192.0.2.2', ssh_user: 'root', proxy: true }],
    guests: [],
  };
}

function renderInventory(inventory: Inventory, configPath = CONFIG_PATH): FileSpec[] {
  return render(buildRoutes(inventory), buildProxyContext(inventory, haproxyDriver), configPath);
}

// One backend block (contract "Backend block") -- the lines every backend
// shares, then the server line.
function backendBlock(name: string, externalPort: number, serverLine: string): string[] {
  return [
    `backend ${name}`,
    '    mode http',
    '    timeout server 1d',
    '    timeout tunnel 1d',
    '    http-request del-header x-authentik- -m beg',
    '    http-request set-header X-Forwarded-For %[src]',
    '    http-request set-header X-Forwarded-Proto https',
    '    http-request set-header X-Forwarded-Host %[req.hdr(host)]',
    `    http-request set-header X-Forwarded-Port ${externalPort}`,
    serverLine,
  ];
}

const EXPECTED_BACKENDS = [
  HEADER,
  '',
  ...backendBlock('bellhop_host_pve1', 443, '    server app 192.0.2.2:8006 ssl verify none'),
  '',
  ...backendBlock('bellhop_guest_web-lxc', 443, '    server app 192.0.2.10:8080'),
  '',
  ...backendBlock(
    'bellhop_externalSite_nas',
    443,
    '    server app 192.0.2.20:443 ssl verify required ca-file /etc/ssl/certs/ca-certificates.crt'
  ),
].join('\n');

const EXPECTED_MAP = [
  HEADER,
  'pve.example.com bellhop_host_pve1',
  'web.example.com bellhop_guest_web-lxc',
  'www.example.com bellhop_guest_web-lxc',
  'nas.example.com bellhop_externalSite_nas',
].join('\n');

function ctx(externalPort = 443): ProxyContext {
  return {
    externalPort,
    tls: {
      certificatePath: '/etc/letsencrypt/live/example.com/fullchain.pem',
      keyPath: '/etc/letsencrypt/live/example.com/privkey.pem',
    },
    certResolver: 'cloudflare',
    tlsSource: 'external',
    acmeDnsProvider: 'cloudflare',
  };
}

function route(overrides: Partial<ProxyRoute> & { owner: ProxyRoute['owner'] }): ProxyRoute {
  return {
    hostnames: [`${overrides.owner.name}.example.com`],
    backend: { ip: '192.0.2.30', port: 80, insecureTls: false },
    auth: { mode: 'ungated' },
    ...overrides,
  };
}

