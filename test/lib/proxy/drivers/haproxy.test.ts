function deps(ssh: FakeSSHClient, configPath = CONFIG_PATH) {
  return { ssh, inventory: exampleInventory(), proxyHost: 'pve1', configPath };
}

test('plan(): preview is the backends file then the map file, each under a ==> <path> <== label, and the payload is both FileSpecs', async () => {
  const inv = exampleInventory();
  const ssh = new FakeSSHClient(() => ({ stdout: '', stderr: '', code: 0 }));
  const plan = await haproxyDriver.plan(buildRoutes(inv), buildProxyContext(inv, haproxyDriver), deps(ssh));
  assert.equal(
    plan.preview,
    `==> ${CONFIG_PATH} <==\n${EXPECTED_BACKENDS}\n\n==> ${MAP_PATH} <==\n${EXPECTED_MAP}`
  );
  assert.deepEqual(
    (plan.payload as FileSpec[]).map((f) => f.content),
    [EXPECTED_BACKENDS, EXPECTED_MAP],
    'the payload carries no preview labels'
  );
  assert.deepEqual(
    (plan.payload as FileSpec[]).map((f) => f.path),
    [CONFIG_PATH, MAP_PATH]
  );
  assert.equal(ssh.history.length, 0, 'plan makes no SSH call');
});

test('apply(): one script to the proxy host that writes both files, validates with haproxy -c over both configs, then reloads', async () => {
  const inv = exampleInventory();
  const ssh = new FakeSSHClient(() => ({ stdout: '', stderr: '', code: 0 }));
  const d = deps(ssh);
  const plan = await haproxyDriver.plan(buildRoutes(inv), buildProxyContext(inv, haproxyDriver), d);
  await haproxyDriver.apply(plan, d);
  assert.equal(ssh.history.length, 1);
  assert.equal(ssh.history[0].sshTarget, '192.0.2.2');
  const script = ssh.history[0].command;
  assert.match(script, /cat > '\/etc\/haproxy\/bellhop\.cfg' <</);
  assert.match(script, /cat > '\/etc\/haproxy\/bellhop\.map' <</);
  assert.ok(
    script.includes("if ! haproxy -c -f /etc/haproxy/haproxy.cfg -f '/etc/haproxy/bellhop.cfg'; then"),
    'validates the operator main config together with the backends file'
  );
  assert.match(script, /^systemctl reload haproxy$/m);
});

