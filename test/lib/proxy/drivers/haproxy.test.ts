// --- T006: executed-script tests (the real apply() script under sh) ----------

function shAvailable(): boolean {
  const result = spawnSync('sh', ['-c', 'exit 0']);
  return result.error === undefined || result.error === null;
}

interface ExecutedApply {
  status: number | null;
  stderr: string;
  cfgPath: string;
  mapFilePath: string;
  haproxyLogPath: string;
  systemctlLogPath: string;
  files: FileSpec[];
}

// Captures the exact script haproxyDriver.apply() sends (through a
// FakeSSHClient), then runs it locally under sh with stub haproxy and
// systemctl binaries first on PATH -- the file-driver executed-script
// exception CLAUDE.md allows. The haproxy stub logs its arguments and exits
// with the given code.
async function runApply(opts: { cfg?: string; map?: string; haproxyExit: number }): Promise<ExecutedApply> {
  const tmpDir = mkdtempSync(join(tmpdir(), 'bellhop-haproxy-driver-'));
  const stubDir = mkdtempSync(join(tmpdir(), 'bellhop-haproxy-driver-stubs-'));
  const posix = (p: string) => p.replace(/\\/g, '/');
  const cfgPath = posix(join(tmpDir, 'bellhop.cfg'));
  const mapFilePath = posix(join(tmpDir, 'bellhop.map'));
  const haproxyLogPath = posix(join(tmpDir, 'haproxy.log'));
  const systemctlLogPath = posix(join(tmpDir, 'systemctl.log'));
  if (opts.cfg !== undefined) writeFileSync(cfgPath, opts.cfg);
  if (opts.map !== undefined) writeFileSync(mapFilePath, opts.map);

  const inv = exampleInventory();
  const ssh = new FakeSSHClient(() => ({ stdout: '', stderr: '', code: 0 }));
  const d = { ssh, inventory: inv, proxyHost: 'pve1', configPath: cfgPath };
  const plan = await haproxyDriver.plan(buildRoutes(inv), buildProxyContext(inv, haproxyDriver), d);
  await haproxyDriver.apply(plan, d);
  const scriptPath = posix(join(tmpDir, 'apply.sh'));
  writeFileSync(scriptPath, ssh.history[0].command);

  const haproxyStub = join(stubDir, 'haproxy');
  writeFileSync(haproxyStub, `#!/bin/sh\necho "$@" >> '${haproxyLogPath}'\nexit ${opts.haproxyExit}\n`);
  chmodSync(haproxyStub, 0o755);
  const systemctlStub = join(stubDir, 'systemctl');
  writeFileSync(systemctlStub, `#!/bin/sh\necho "$@" >> '${systemctlLogPath}'\n`);
  chmodSync(systemctlStub, 0o755);

  const env = { ...process.env, PATH: `${stubDir}${delimiter}${process.env.PATH}` };
  const result = spawnSync('sh', [scriptPath], { env });
  return {
    status: result.status,
    stderr: String(result.stderr),
    cfgPath,
    mapFilePath,
    haproxyLogPath,
    systemctlLogPath,
    files: plan.payload as FileSpec[],
  };
}

const OLD_CFG = `${HEADER}\n\nbackend bellhop_guest_old\n    mode http\n    server app 192.0.2.99:80\n`;
const OLD_MAP = `${HEADER}\nold.example.com bellhop_guest_old\n`;

test('haproxyDriver apply script, executed: a failed "haproxy -c" restores both existing files byte for byte, exits non-zero, and never reloads', async (t) => {
  if (!shAvailable()) {
    t.skip('sh not found on PATH -- cannot execute the generated script');
    return;
  }
  const run = await runApply({ cfg: OLD_CFG, map: OLD_MAP, haproxyExit: 1 });
  assert.notEqual(run.status, 0, `expected a non-zero exit, stderr: ${run.stderr}`);
  assert.equal(readFileSync(run.cfgPath, 'utf8'), OLD_CFG, 'the backends file must be restored byte for byte');
  assert.equal(readFileSync(run.mapFilePath, 'utf8'), OLD_MAP, 'the map file must be restored byte for byte');
  assert.ok(existsSync(run.haproxyLogPath), 'haproxy -c must have run');
  assert.ok(!existsSync(run.systemctlLogPath), 'systemctl must not have been called');
});

test('haproxyDriver apply script, executed: a failed "haproxy -c" removes a map file that did not exist before, and restores the backends file', async (t) => {
  if (!shAvailable()) {
    t.skip('sh not found on PATH -- cannot execute the generated script');
    return;
  }
  const run = await runApply({ cfg: OLD_CFG, haproxyExit: 1 });
  assert.notEqual(run.status, 0, `expected a non-zero exit, stderr: ${run.stderr}`);
  assert.equal(readFileSync(run.cfgPath, 'utf8'), OLD_CFG);
  assert.ok(!existsSync(run.mapFilePath), 'a map file that did not exist before must be removed again');
  assert.ok(!existsSync(run.systemctlLogPath), 'systemctl must not have been called');
});

test('haproxyDriver apply script, executed: a passing "haproxy -c" writes both files and reloads haproxy once', async (t) => {
  if (!shAvailable()) {
    t.skip('sh not found on PATH -- cannot execute the generated script');
    return;
  }
  const run = await runApply({ cfg: OLD_CFG, map: OLD_MAP, haproxyExit: 0 });
  assert.equal(run.status, 0, `expected exit 0, stderr: ${run.stderr}`);
  // The heredoc that writes an 'owned' file always ends with a newline.
  assert.equal(readFileSync(run.cfgPath, 'utf8'), `${run.files[0].content}\n`);
  assert.equal(readFileSync(run.mapFilePath, 'utf8'), `${run.files[1].content}\n`);
  assert.equal(readFileSync(run.haproxyLogPath, 'utf8').trim(), `-c -f /etc/haproxy/haproxy.cfg -f ${run.cfgPath}`);
  assert.equal(readFileSync(run.systemctlLogPath, 'utf8').trim(), 'reload haproxy');
});

test('haproxyDriver apply script, executed: an existing map file without the generated header is refused before writing, leaving both files untouched', async (t) => {
  if (!shAvailable()) {
    t.skip('sh not found on PATH -- cannot execute the generated script');
    return;
  }
  const foreignMap = 'example.com some_other_backend\n';
  const run = await runApply({ cfg: OLD_CFG, map: foreignMap, haproxyExit: 0 });
  assert.notEqual(run.status, 0, `expected a non-zero exit, stderr: ${run.stderr}`);
  assert.equal(readFileSync(run.cfgPath, 'utf8'), OLD_CFG, 'the backends file must be untouched');
  assert.equal(readFileSync(run.mapFilePath, 'utf8'), foreignMap, 'the foreign map file must be untouched');
  assert.ok(!existsSync(run.haproxyLogPath), 'haproxy -c must not have run');
  assert.ok(!existsSync(run.systemctlLogPath), 'systemctl must not have been called');
  assert.ok(run.stderr.includes(run.mapFilePath), 'the refusal names the map path');
  assert.match(run.stderr, /proxyConfigPath/);
});

test('haproxyDriver apply script, executed: an existing backends file carrying the nginx driver header is refused before writing, leaving both files untouched', async (t) => {
  if (!shAvailable()) {
    t.skip('sh not found on PATH -- cannot execute the generated script');
    return;
  }
  const nginxFile = `${NGINX_HEADER}\n\nserver {\n    listen 443 ssl;\n}\n`;
  const run = await runApply({ cfg: nginxFile, map: OLD_MAP, haproxyExit: 0 });
  assert.notEqual(run.status, 0, `expected a non-zero exit, stderr: ${run.stderr}`);
  assert.equal(readFileSync(run.cfgPath, 'utf8'), nginxFile, 'the nginx-owned file must be untouched');
  assert.equal(readFileSync(run.mapFilePath, 'utf8'), OLD_MAP, 'the map file must be untouched');
  assert.ok(!existsSync(run.haproxyLogPath), 'haproxy -c must not have run');
  assert.ok(!existsSync(run.systemctlLogPath), 'systemctl must not have been called');
  assert.ok(run.stderr.includes(run.cfgPath), 'the refusal names the backends file path');
});
